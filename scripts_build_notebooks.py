"""Generates approach 2's Jupyter notebooks as plain .ipynb JSON.

Run locally after editing src/*.py:  python scripts_build_notebooks.py

Kaggle (and a borrowed H100) cannot import this repo's `src/`, so every notebook
embeds the modules it needs with %%writefile cells, as the package `irlib/`
(SimuHome has its own top-level `src` package; two same-named packages in one
kernel shadow each other). The modules use relative imports, so no rewriting is
needed. Notebooks:

  01_train_parser_v3.ipynb   GPU only (Kaggle T4 or the H100): builds the v3 labels,
                             LoRA-trains the parser, evaluates it, and writes
                             parse_cache_v3.json for every QT4 request.
  00_approach2_pipeline.ipynb  the E1 experiment. CPU is enough when a parse cache is
                             attached (from 01, or one built from the v2 adapter).
"""
import json
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
NB_DIR = os.path.join(ROOT, "notebooks")
SRC_DIR = os.path.join(ROOT, "src")


def md(*lines):
    return {"cell_type": "markdown", "metadata": {}, "source": [l + "\n" for l in lines]}


def code(*lines):
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": [l + "\n" for l in lines]}


def writefile_cell(module: str):
    with open(os.path.join(SRC_DIR, module), "r", encoding="utf-8") as f:
        content = f.read()
    lines = [f"%%writefile irlib/{module}"] + content.splitlines()
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": [l + "\n" for l in lines]}


def notebook(cells):
    return {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3.11"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def save(name, cells):
    os.makedirs(NB_DIR, exist_ok=True)
    path = os.path.join(NB_DIR, name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(notebook(cells), f, indent=1)
    print("wrote", path)


